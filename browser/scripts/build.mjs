import {build} from 'esbuild';
import fs from 'node:fs';
fs.rmSync('dist',{recursive:true,force:true});
fs.cpSync('public','dist',{recursive:true});
await build({entryPoints:{'browser-app':'src/app.js','browser-worker':'src/worker.js'},bundle:true,splitting:true,conditions:['onnxruntime-web-use-extern-wasm'],format:'esm',outdir:'dist',target:'es2022',minify:true,sourcemap:true,legalComments:'eof'});
fs.mkdirSync('dist/ort',{recursive:true});
for(const name of ['ort-wasm-simd-threaded.mjs','ort-wasm-simd-threaded.wasm'])fs.copyFileSync('node_modules/onnxruntime-web/dist/'+name,'dist/ort/'+name);
fs.copyFileSync('third_party/onnxruntime/LICENSE','dist/ONNX-RUNTIME-LICENSE.txt');
fs.copyFileSync('third_party/onnxruntime/ThirdPartyNotices.txt','dist/ONNX-RUNTIME-THIRD-PARTY-NOTICES.txt');
for(const name of ['LICENSE','THIRD_PARTY_NOTICES.md'])fs.copyFileSync(name,'dist/'+name);
fs.copyFileSync('node_modules/mediabunny/LICENSE','dist/MEDIABUNNY-LICENSE.txt');
fs.writeFileSync('dist/.nojekyll','');
console.log('Browser-only site built in dist. No processing server is required.');
